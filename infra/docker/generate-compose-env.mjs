#!/usr/bin/env node
// Creates infra/docker/compose.env with fresh random secrets and an RS256 keypair for running the
// production-mode stack locally. The file is git-ignored; never commit it.
//
//   node infra/docker/generate-compose-env.mjs            # refuses to overwrite
//   node infra/docker/generate-compose-env.mjs --force    # regenerate (existing sessions end)
import { generateKeyPairSync, randomBytes } from 'node:crypto';
import { existsSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const target = join(dirname(fileURLToPath(import.meta.url)), 'compose.env');
if (existsSync(target) && !process.argv.includes('--force')) {
  console.error(`${target} already exists; pass --force to regenerate it.`);
  process.exit(1);
}

const secret = () => randomBytes(32).toString('hex');
const { privateKey, publicKey } = generateKeyPairSync('rsa', {
  modulusLength: 2048,
  publicKeyEncoding: { type: 'spki', format: 'pem' },
  privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
});
const oneLine = (pem) => pem.trim().replace(/\n/g, '\\n');

const lines = [
  '# Generated by generate-compose-env.mjs. Local use only; git-ignored.',
  `POSTGRES_PASSWORD=${secret()}`,
  `APP_DB_PASSWORD=${secret()}`,
  `JWT_ACCESS_SECRET=${secret()}`,
  `JWT_REFRESH_SECRET=${secret()}`,
  `DATABASE_ENCRYPTION_KEY=${secret()}`,
  `WHATSAPP_WEBHOOK_VERIFY_TOKEN=${secret()}`,
  `METRICS_TOKEN=${secret()}`,
  `JWT_PRIVATE_KEY=${oneLine(privateKey)}`,
  `JWT_PUBLIC_KEY=${oneLine(publicKey)}`,
  '',
  '# Optional integrations: fill in to send real WhatsApp, email and payments',
  'WHATSAPP_PHONE_NUMBER_ID=',
  'WHATSAPP_API_TOKEN=',
  'WHATSAPP_APP_SECRET=',
  'SMTP_HOST=',
  'SMTP_USER=',
  'SMTP_PASS=',
  'RAZORPAY_KEY_ID=',
  'RAZORPAY_KEY_SECRET=',
  'RAZORPAY_WEBHOOK_SECRET=',
  'OPENAI_API_KEY=',
  'ANTHROPIC_API_KEY=',
  'GEMINI_API_KEY=',
];
writeFileSync(target, lines.join('\n') + '\n', { mode: 0o600 });
console.log(`Wrote ${target}`);
